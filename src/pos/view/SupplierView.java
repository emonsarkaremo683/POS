    public void showAllSupplier() {
        List<Supplier> list = dao.findAll();

        String[] columns = {"Sl", "Name", "Cell", "Contact Person", "Contact Cell", "Address"};

        DefaultTableModel model = new DefaultTableModel();

        model.setColumnIdentifiers(columns);
        tblSupplierShow.setModel(model);

        for (Supplier s : list) {
            model.addRow(new Object[]{
                s.getId(),
                s.getName(),
                s.getCell(),
                s.getContactPersonName(),
                s.getContactPersonCell(),
                s.getAddress()
            });

        }

    }

