    private void btnSupplierSaveMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSupplierSaveMouseClicked
        // TODO add your handling code here:
        String name = txtSupplierName.getText().trim();
        String cell = txtSupplierCell.getText().trim();
        String contactPersonName = txtSupplierContactPersonName.getText().trim();
        String contactPersonCell = txtSupplierContactPersonCell.getText().trim();
        String address = txtSupplierAddress.getText().trim();

        Supplier supplier = new Supplier(name, cell, contactPersonName, contactPersonCell, address);
        dao.save(supplier);
        clearData();
        showAllSupplier();

    }//GEN-LAST:event_btnSupplierSaveMouseClicked

    private void tblSupplierShowMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSupplierShowMouseClicked
        // TODO add your handling code here:
        int selectedRow = tblSupplierShow.getSelectedRow();

        String id = tblSupplierShow.getModel().getValueAt(selectedRow, 0).toString();
        String name = tblSupplierShow.getModel().getValueAt(selectedRow, 1).toString();
        String cell = tblSupplierShow.getModel().getValueAt(selectedRow, 2).toString();
        String contactPersonName = tblSupplierShow.getModel().getValueAt(selectedRow, 3).toString();
        String contactPersonCell = tblSupplierShow.getModel().getValueAt(selectedRow, 4).toString();
        String address = tblSupplierShow.getModel().getValueAt(selectedRow, 5).toString();

        txtSupplierId.setText(id);
        txtSupplierName.setText(name);
        txtSupplierCell.setText(cell);
        txtSupplierContactPersonName.setText(contactPersonName);
        txtSupplierContactPersonCell.setText(contactPersonCell);
        txtSupplierAddress.setText(address);
        

    }//GEN-LAST:event_tblSupplierShowMouseClicked

    private void btnSupplierUpdateMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSupplierUpdateMouseClicked
        // TODO add your handling code here:
        int id = Integer.parseInt(txtSupplierId.getText());
        String name = txtSupplierName.getText().trim();
        String cell = txtSupplierCell.getText().trim();
        String contactPersonName = txtSupplierContactPersonName.getText().trim();
        String contactPersonCell = txtSupplierContactPersonCell.getText().trim();
        String address = txtSupplierAddress.getText().trim();
        
        Supplier s = new Supplier(id, name, cell, contactPersonName, contactPersonCell, address);
        
        dao.update(s);        
        showAllSupplier();
        clearData();
     
        
    }//GEN-LAST:event_btnSupplierUpdateMouseClicked

