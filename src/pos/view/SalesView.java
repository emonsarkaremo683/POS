    void generateSalesTable() {
        DefaultTableModel model = new DefaultTableModel();

        String columns[] = {"Product", "Qty", "Unit Price", "Total", "Discount Rate", "Discount", "Actual"};

        model.setColumnIdentifiers(columns);

        tblSalesItem.setModel(model);

    }

    void loadAllProduct() {
        List<String> productNames = pd.getAllProductName();
        comboSalesProduct.removeAllItems();
        comboSalesProduct.addItem("--Select Product--");

        for (String p : productNames) {
            comboSalesProduct.addItem(p);
        }
    }

    void calculateGrandTotal() {

        DefaultTableModel model = (DefaultTableModel) tblSalesItem.getModel();

        double sum = 0;

        for (int i = 0; i < model.getRowCount(); i++) {
            double value = Double.parseDouble(model.getValueAt(i, 6).toString());
            sum += value;
        }

        txtSalesTotalAmount.setText(String.format("%.2f", sum));
    }

    void addItemToTable(SalesItem item) {

        DefaultTableModel model = (DefaultTableModel) tblSalesItem.getModel();

        model.addRow(new Object[]{
            item.getProductName(),
            item.getQuantity(),
            item.getUnitPrice(),
            item.getTotalPrice(),
            item.getDiscountRate(),
            item.getDiscount(),
            item.getActualPrice()
        });
//calculateTotal();
    }

