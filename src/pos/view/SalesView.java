    private void txtSalesQuantityFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtSalesQuantityFocusLost
        // TODO add your handling code here:
        try {
            String qtyText = txtSalesQuantity.getText().trim();
            String priceText = txtSalesUnitPrice.getText().trim();

            if (qtyText.isEmpty() || priceText.isEmpty()) {
                txtSalesTotalPrice.setText("");
                return;
            }

            double quantity = Double.parseDouble(qtyText);
            double unitPrice = Double.parseDouble(priceText);

            double totalPrice = salesUtil.getTotalSalesPrice(unitPrice, quantity);

            txtSalesTotalPrice.setText(String.valueOf(totalPrice));

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter valid numeric values.");
            txtSalesTotalPrice.setText("");
        }
    }//GEN-LAST:event_txtSalesQuantityFocusLost

    private void txtSalesDiscountRateFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtSalesDiscountRateFocusLost
        // TODO add your handling code here:
        try {
            String qtyText = txtSalesQuantity.getText().trim();
            String priceText = txtSalesUnitPrice.getText().trim();
            String discountRateText = txtSalesDiscountRate.getText().trim();

            if (qtyText.isEmpty() || priceText.isEmpty() || discountRateText.isEmpty()) {
                return;
            }

            double quantity = Double.parseDouble(qtyText);
            double unitPrice = Double.parseDouble(priceText);
            double discountRate = Double.parseDouble(discountRateText);

            double totalPrice = salesUtil.getTotalSalesPrice(unitPrice, quantity);

            double discount = salesUtil.getDiscountAmount(totalPrice, discountRate);
            txtSalesDiscount.setText(String.valueOf(discount));

            double actualPrice = salesUtil.getActualPrice(totalPrice, discount);
            txtSalesActualPrice.setText(String.valueOf(actualPrice));

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter valid numeric values.");
            txtSalesDiscount.setText("");
            txtSalesActualPrice.setText("");
        }

    }//GEN-LAST:event_txtSalesDiscountRateFocusLost

    private void btnSalesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSalesMouseClicked
       
        double totalPrice = Double.parseDouble(txtSalesTotalAmount.getText().trim());        
        String customerCell = txtSalesCustomerCell.getText().trim();
        String invoiceNo = "INV-" + txtSalesInvoiceNo.getText().trim();
        Sales sales = new Sales(invoiceNo, customerCell, totalPrice);

        // Save sales and get generated ID
        int salesId = salesDao.save(sales);

        DefaultTableModel model = (DefaultTableModel) tblSalesItem.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {

            String productName = model.getValueAt(i, 0).toString();

            int productId = pd.findIdByName(productName);

            //int productId = Integer.parseInt(model.getValueAt(i, 0).toString());
            double qty = Double.parseDouble(model.getValueAt(i, 1).toString());
            double unitPrice = Double.parseDouble(model.getValueAt(i, 2).toString());
            double total = Double.parseDouble(model.getValueAt(i, 3).toString());
            double discountRate = Double.parseDouble(model.getValueAt(i, 4).toString());
            double discountAmount = Double.parseDouble(model.getValueAt(i, 5).toString());
            double actual = Double.parseDouble(model.getValueAt(i, 6).toString());

            SalesItem item = new SalesItem();
            item.setSalesId(salesId);
            item.setProductId(productId);
            item.setQuantity(qty);
            item.setUnitPrice(unitPrice);
            item.setTotalPrice(total);
            item.setDiscount(discountAmount);
            item.setActualPrice(actual);
            item.setDiscountRate(discountRate);

            salesItemDao.saveSalesItem(item);
        }

        clearData();

        txtSalesCustomerCell.setText("");
        txtSalesInvoiceNo.setText("");
        txtSalesTotalAmount.setText("");
        clearTable();

    }//GEN-LAST:event_btnSalesMouseClicked

